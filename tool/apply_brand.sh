#!/usr/bin/env bash
# Applies the brand to native (Android / iOS / web) files that Dart can't
# reach at runtime: the app name under the icon and the native splash screen.
#
# Android (preBuild) and iOS (Run Script phase) builds call this
# automatically. The splash only regenerates when the brand or its splash
# config changed since the last run (recorded in tool/.splash_brand).
#
#   tool/apply_brand.sh            # same brand AppBrand resolves to
#   tool/apply_brand.sh kfon       # explicit brand
#   tool/apply_brand.sh --force    # regenerate the splash even if up to date
#   tool/apply_brand.sh --ios-built-plist <path>
#                                  # only set the name in a built Info.plist
set -euo pipefail
cd "$(dirname "$0")/.."

force=false
brand=""
built_plist=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --force) force=true ;;
    --ios-built-plist) built_plist="$2"; shift ;;
    *) brand="$1" ;;
  esac
  shift
done

# Same order as AppBrand.brand: --dart-define=BRAND first (Flutter passes
# dart-defines to native builds as base64 entries in DART_DEFINES), then
# the defaultValue in app_brand.dart.
if [[ -z "$brand" && -n "${DART_DEFINES:-}" ]]; then
  IFS=',' read -ra defines <<< "$DART_DEFINES"
  for d in "${defines[@]}"; do
    decoded="$(printf '%s' "$d" | base64 --decode 2>/dev/null || true)"
    if [[ "$decoded" == BRAND=* ]]; then brand="${decoded#BRAND=}"; fi
  done
fi
if [[ -z "$brand" ]]; then
  brand="$(grep -m1 'defaultValue:' lib/core/constant/app_brand.dart \
    | sed -E "s/.*defaultValue:[[:space:]]*'([^']*)'.*/\1/")"
fi

# Same rule as AppBrand: only 'kfon' builds KFON, anything else is RailWire.
[[ "$brand" == "kfon" ]] || brand="railwire"

# ---- App name under the icon (matches AppBrand.appName + " Subscriber") ----
if [[ "$brand" == "kfon" ]]; then
  display_name="KFON Subscriber"
else
  display_name="RailWire Subscriber"
fi

set_plist_name() {
  local plist="$1"
  if [[ "$(/usr/libexec/PlistBuddy -c 'Print :CFBundleDisplayName' "$plist" 2>/dev/null)" != "$display_name" ]]; then
    /usr/libexec/PlistBuddy -c "Set :CFBundleDisplayName $display_name" "$plist"
  fi
}

# Called from the iOS "Thin Binary" phase, after Xcode has processed
# Info.plist, so the name is right on the very first build.
if [[ -n "$built_plist" ]]; then
  set_plist_name "$built_plist"
  exit 0
fi

# Only write when the content differs, so unchanged builds stay incremental.
write_if_changed() {
  local file="$1" content="$2"
  if [[ ! -f "$file" || "$(cat "$file")" != "$content" ]]; then
    printf '%s\n' "$content" > "$file"
  fi
}

write_if_changed android/app/src/main/res/values/strings.xml \
"<?xml version=\"1.0\" encoding=\"utf-8\"?>
<!-- Generated by tool/apply_brand.sh. Don't edit; change the brand instead. -->
<resources>
    <string name=\"app_name\">$display_name</string>
</resources>"

[[ "$OSTYPE" == darwin* ]] && set_plist_name ios/Runner/Info.plist

if [[ -f web/manifest.json ]]; then
  sed -i.bak -E "s/(\"(short_)?name\": )\"[^\"]*\"/\1\"$display_name\"/" web/manifest.json
  rm -f web/manifest.json.bak
fi
if [[ -f web/index.html ]]; then
  sed -i.bak -E \
    -e "s#<title>[^<]*</title>#<title>$display_name</title>#" \
    -e "s#(apple-mobile-web-app-title\" content=\")[^\"]*#\1$display_name#" \
    web/index.html
  rm -f web/index.html.bak
fi

# ---- Native splash ----
config="flutter_native_splash-$brand.yaml"
stamp_file="tool/.splash_brand"

# Fingerprint = brand + its config + the splash images it references.
images="$(sed -nE 's/^[[:space:]]*image:[[:space:]]*([^[:space:]#]+).*/\1/p' "$config")"
# shellcheck disable=SC2086
hash_cmd="shasum"; command -v shasum >/dev/null || hash_cmd="sha1sum"  # Linux CI
stamp="$brand $(cat "$config" $images | $hash_cmd | cut -d' ' -f1)"

if [[ "$force" == false && -f "$stamp_file" && "$(cat "$stamp_file")" == "$stamp" ]]; then
  echo "Native splash already up to date for '$brand'"
  exit 0
fi

echo "Generating native splash for '$brand' from $config"
dart_bin="dart"
[[ -n "${FLUTTER_ROOT:-}" ]] && dart_bin="$FLUTTER_ROOT/bin/dart"
"$dart_bin" run flutter_native_splash:create --path="$config"
# The generator leaves blank lines in index.html on every run; squeeze them
# so brand switches don't keep growing the diff.
if [[ -f web/index.html ]]; then
  awk 'NF { blank = 0; print; next } !blank++ { print "" }' web/index.html > web/index.html.tmp
  mv web/index.html.tmp web/index.html
fi
echo "$stamp" > "$stamp_file"
